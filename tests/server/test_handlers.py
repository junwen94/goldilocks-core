class TestInspect:
    def test_returns_the_real_structure_inspection(
        self, real_assets, silicon_cif
    ) -> None:
        document = InlineStructureDocument(structure_content=silicon_cif)

        inspection = _handlers.inspect(document)

        assert inspection["structure"]["reduced_formula"] == "Si"


class TestMagneticOrderings:
    def test_lists_the_fm_candidate_unranked_by_default(self, silicon_cif) -> None:
        document = MagneticOrderingsRequestDocument(structure_content=silicon_cif)

        result = _handlers.magnetic_orderings(document)

        assert result["ranked"] is False
        [candidate] = result["candidates"]
        assert candidate["label"] == "fm"
        assert candidate["formula"] == "Si"
        assert candidate["natoms"] == 8
        assert candidate["energy_per_atom_ev"] is None
        assert candidate["status"] is None
        assert candidate["is_recommended"] is False
        # A candidate is generated by its label on the listed structure
        # (#170): no structure of its own to send back.
        assert candidate["overrides"] == {"magnetic_ordering": "fm"}
        assert "structure_content" not in candidate
        assert "structure_format" not in candidate
        assert result["warnings"] == []

    def test_rank_with_mmace_degrades_with_a_warning_when_unconfigured(
        self, silicon_cif, monkeypatch
    ) -> None:
        monkeypatch.delenv("GOLDILOCKS_MACE_BACKBONE", raising=False)
        document = MagneticOrderingsRequestDocument(
            structure_content=silicon_cif, rank_with_mmace=True
        )

        result = _handlers.magnetic_orderings(document)

        assert result["ranked"] is False
        assert len(result["warnings"]) == 1
        assert result["warnings"][0]["code"] == "magnetic.ordering_ranking_unavailable"


class TestExplain:
    def test_returns_records_and_warnings(self, real_assets, silicon_cif) -> None:
        document = ComputeRequestDocument(structure_content=silicon_cif, hpc="scarf")

        result = _handlers.explain(document)

        assert result["records"]["functional"]["value"] == "PBEsol"
        assert result["records"]["functional"]["status"] == "resolved"
        assert isinstance(result["warnings"], list)
        assert all(
            warning.keys() == {"code", "level", "category", "message", "record"}
            for warning in result["warnings"]
        )

    def test_never_raises_for_a_scientifically_incomplete_request(
        self, real_assets, silicon_cif
    ) -> None:
        """The "diagnosis is always available" promise -- an unknown
        pseudo_table_id degrades every dependent field to Blocked, but
        explain() itself must still succeed."""
        document = ComputeRequestDocument(
            structure_content=silicon_cif,
            hpc="scarf",
            overrides={"pseudo_table_id": "does-not-exist"},
        )

        result = _handlers.explain(document)

        assert result["records"]["pseudo_table"]["status"] == "unavailable"
        assert result["records"]["cutoffs"]["status"] == "blocked"

    @pytest.mark.parametrize(
        ("task", "overrides", "expected"),
        [
            pytest.param("scf_single_point", {}, ["is not installed"], id="scf"),
            pytest.param("dos", {}, ["is not installed"], id="dos"),
            pytest.param(
                "relax",
                {"fix_bottom_layers": 2},
                ["is not installed", "fix_bottom_layers requires a slab"],
                id="relax",
            ),
            pytest.param(
                "vc-relax",
                {"ion_dynamics": "damp"},
                ["is not installed", "vc-relax requires ion_dynamics='bfgs'"],
                id="vc-relax",
            ),
        ],
    )
    def test_blocking_is_the_verdict_run_refuses_with(
        self, silicon_cif, task, overrides, expected
    ) -> None:
        """#165: explain reports run's verdict (advise, then the task's own
        check) before any files are requested. No real assets: the isolated
        asset root has no pseudopotential table installed, a deterministic
        blocker; the relax overrides add each task's named check rule."""
        document = ComputeRequestDocument(
            structure_content=silicon_cif,
            hpc="scarf",
            task=task,
            overrides=overrides,
        )

        result = _handlers.explain(document)

        with pytest.raises(AdviceIncomplete) as excinfo:
            _handlers.run(document)
        reasons = list(dict.fromkeys(excinfo.value.report.blocking))
        assert result["blocking"] == reasons
        assert len(reasons) == len(expected)
        for reason, fragment in zip(reasons, expected, strict=True):
            assert fragment in reason

    def test_blocking_is_empty_when_run_generates(
        self, real_assets, silicon_cif
    ) -> None:
        document = ComputeRequestDocument(structure_content=silicon_cif, hpc="scarf")

        result = _handlers.explain(document)

        assert result["blocking"] == []
        summary, _bundle_input = _handlers.run(document)
        assert "scf.in" in summary["files"]

    def test_blocking_names_a_cross_parameter_rule(
        self, real_assets, silicon_cif
    ) -> None:
        document = ComputeRequestDocument(
            structure_content=silicon_cif, hpc="scarf", overrides={"npool": 7}
        )

        result = _handlers.explain(document)

        with pytest.raises(AdviceIncomplete) as excinfo:
            _handlers.run(document)
        assert result["blocking"] == list(dict.fromkeys(excinfo.value.report.blocking))
        [reason] = result["blocking"]
        assert reason.startswith("npool=7 does not divide ntasks=")


class TestRun:
    def test_produces_a_complete_bundle_summary(self, real_assets, silicon_cif) -> None:
        document = ComputeRequestDocument(structure_content=silicon_cif, hpc="scarf")

        summary, bundle_input = _handlers.run(document)

        assert "scf.in" in summary["files"]
        assert "submit.sh" in summary["files"]
        assert any(path.endswith(".upf") for path in summary["files"])
        assert summary["records"]["functional"]["value"] == "PBEsol"
        assert any(bundle_input.records)

    def test_raises_advice_incomplete_when_blocked(
        self, real_assets, silicon_cif
    ) -> None:
        document = ComputeRequestDocument(
            structure_content=silicon_cif,
            hpc="scarf",
            overrides={"pseudo_table_id": "does-not-exist"},
        )

        with pytest.raises(AdviceIncomplete) as excinfo:
            _handlers.run(document)

        # AdviceIncomplete's own dedup (service/_generate.py) -- must not
        # repeat the same root cause once per field it blocks.
        message = str(excinfo.value)
        assert message.count("unknown pseudopotential table") == 1

    def test_overrides_flow_through_to_the_generated_input(
        self, real_assets, silicon_cif
    ) -> None:
        document = ComputeRequestDocument(
            structure_content=silicon_cif,
            hpc="scarf",
            overrides={"functional": "PBE"},
        )

        summary, _bundle_input = _handlers.run(document)

        assert summary["records"]["functional"]["value"] == "PBE"
        assert summary["records"]["functional"]["source"] == "human"

    @pytest.mark.parametrize(
        ("task", "overrides"),
        [
            ("scf_single_point", {"k_distance": 0.2}),
            ("dos", {"k_distance": 0.2, "steps.dos.delta_e": 0.05}),
            ("relax", {"nstep": 123}),
            ("vc-relax", {"press": 10.0, "steps.vc-relax.nstep": 50}),
        ],
    )
    def test_the_manifest_records_the_request_as_submitted(
        self, silicon_fixture_table, silicon_cif, task, overrides
    ) -> None:
        """#176: goldilocks.json named no code, task, engine version,
        overrides or input structure. Each task's bundle now records the
        request it answers: the overrides exactly as the body sent them and
        the sha256 of the submitted structure_content."""
        document = ComputeRequestDocument(
            structure_content=silicon_cif,
            structure_name="Si.cif",
            hpc="scarf",
            task=task,
            overrides=overrides,
        )

        _summary, bundle_input = _handlers.run(document)

        (manifest,) = (
            strict_json(file["content"])
            for file in bundle_files(bundle_input)
            if file["path"] == "goldilocks.json"
        )
        content = silicon_cif.encode("utf-8")
        assert manifest["schema_version"] == 2
        assert manifest["request"] == {
            "code": "quantum_espresso",
            "task": task,
            "hpc": "scarf",
            "core_version": version("goldilocks-core"),
            "overrides": overrides,
            "structure": {
                "name": "Si.cif",
                "format": "cif",
                "sha256": hashlib.sha256(content).hexdigest(),
                "size_bytes": len(content),
            },
        }


